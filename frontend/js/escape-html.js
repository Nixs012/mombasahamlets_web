/**
 * escape-html.js
 * Lightweight HTML escaping utility for safe innerHTML insertion.
 * Usage: escapeHtml(userString) returns escaped string.
 */

function escapeHtml(str) {
    if (str === null || str === undefined) return '';
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
}
